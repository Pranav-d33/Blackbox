/**
 * Measure 0G Storage (Galileo) against Arkiv (Rabdi) on the same bytes: real Blackbox log entries.
 *   npm run arkiv:bench -- --n 5
 * Writes arkiv/benchmark.md. Both are testnets, so fees are shown in their native units and gas, not
 * dollars: the honest comparisons are latency, gas, bytes per transaction and what each can answer.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { createWalletClient, ExpirationTime } from "@arkiv-network/sdk";
import { rabdi } from "@arkiv-network/sdk/chains";
import { eq } from "@arkiv-network/sdk/query";
import { i32 } from "@arkiv-network/sdk/schema";
import { JsonRpcProvider, formatEther as fmt0g, toUtf8Bytes } from "ethers";
import { formatEther, http, type Hex } from "viem";
import { privateKeyToAccount } from "viem/accounts";
import { REPO_ROOT, loadConfig } from "../src/config";
import { canonicalJson } from "../src/lib/canonical";
import { ZgStorage } from "../src/storage";
import { Blob } from "../src/arkiv/schema";
import { arkivPublic, mirroredBlob } from "../src/arkiv/read";

const cfg = loadConfig();
if (!cfg.arkiv) throw new Error("set ARKIV=rabdi");
if (cfg.storage.mode !== "0g") throw new Error("set STORAGE=0g (the benchmark writes to 0G Storage on Galileo)");
const N = Number(process.argv.find((_, i, a) => a[i - 1] === "--n") ?? 5);

// real entries from the most recent mission with decisions
const dir = join(cfg.dataDir, "missions");
const recs = readdirSync(dir).map((f) => JSON.parse(readFileSync(join(dir, f), "utf8"))).filter((r) => r.entries?.some((e: any) => e?.kind === "decision"));
if (!recs.length) throw new Error("fly one mission first: the benchmark uses real log entries");
const rec = recs.sort((a, b) => b.createdAt.localeCompare(a.createdAt))[0];
const mid: string = rec.id;
const blobs: Uint8Array[] = rec.entries.filter(Boolean).slice(0, N).map((e: any) => toUtf8Bytes(canonicalJson({ ...e, bench: Date.now() })));
const size = blobs.reduce((s: number, b: Uint8Array) => s + b.length, 0);
console.log(`${blobs.length} entries from mission ${rec.id.slice(0, 10)}…, ${size} bytes in all`);

const ms = () => performance.now();
const med = (xs: number[]) => [...xs].sort((a, b) => a - b)[Math.floor(xs.length / 2)];

// ---- 0G Storage
const zg = new ZgStorage(cfg.storage);
const galileo = new JsonRpcProvider(cfg.storage.rpc, cfg.storage.network.chainId, { staticNetwork: true });
const z = { write: [] as number[], read: [] as number[], gas: 0n, fee: 0n, roots: [] as string[] };
for (const b of blobs) {
  const t = ms();
  const s = await zg.upload(b);
  z.write.push(ms() - t);
  z.roots.push(s.root);
  if (s.txHash) {
    const [tx, rc] = await Promise.all([galileo.getTransaction(s.txHash), galileo.getTransactionReceipt(s.txHash)]);
    z.gas += rc!.gasUsed;
    z.fee += rc!.gasUsed * (rc!.gasPrice ?? 0n) + (tx?.value ?? 0n); // gas + the storage fee paid to the flow contract
  }
  console.log(`  0G Storage  ${(ms() - t).toFixed(0)} ms  root ${s.root.slice(0, 12)}…`);
}
for (const r of z.roots) {
  const t = ms();
  await zg.download(r);
  z.read.push(ms() - t);
}

// ---- Arkiv: one entity per transaction, then all in one batch
const pub = arkivPublic(cfg.arkiv.accessKey);
const w = createWalletClient({ chain: rabdi({ accessKey: cfg.arkiv.accessKey }), transport: http(), account: privateKeyToAccount(cfg.arkiv.key as Hex) });
const ak = { write: [] as number[], read: [] as number[], gas: 0n, fee: 0n, batchMs: 0, batchGas: 0n, batchFee: 0n };
const values = (b: Uint8Array, i: number) => ({ root: z.roots[i].toLowerCase(), kind: "entry", mission: mid, seq: i32(i), content: b });
for (const [i, b] of blobs.entries()) {
  const t = ms();
  const r = await w.createEntity(Blob, values(b, i), { expiration: ExpirationTime.fromDays(1) });
  const rc = await pub.waitForTransactionReceipt({ hash: r.txHash });
  ak.write.push(ms() - t);
  ak.gas += rc.gasUsed;
  ak.fee += rc.gasUsed * rc.effectiveGasPrice;
  console.log(`  Arkiv       ${(ms() - t).toFixed(0)} ms  entity ${r.entityKey.slice(0, 12)}…`);
}
{
  const t = ms();
  const r = await w.executeBatch({ creates: blobs.map((b, i) => ({ schema: Blob, values: values(b, i), expiration: ExpirationTime.fromDays(1) })) } as any);
  const rc = await pub.waitForTransactionReceipt({ hash: r.txHash });
  ak.batchMs = ms() - t;
  ak.batchGas = rc.gasUsed;
  ak.batchFee = rc.gasUsed * rc.effectiveGasPrice;
}
for (const r of z.roots) {
  const t = ms();
  await mirroredBlob(pub, r);
  ak.read.push(ms() - t);
}
const qt = ms();
const q = pub.count().from(Blob).where(eq("mission", mid));
const matched = await q.fetch();
const queryMs = ms() - qt;

const row = (k: string, a: string, b: string) => `| ${k} | ${a} | ${b} |`;
const md = `# 0G Storage vs Arkiv, measured

Generated by \`npm run arkiv:bench -- --n ${blobs.length}\` on ${new Date().toISOString().slice(0, 16)} UTC. ${blobs.length} real Blackbox log entries (${size} bytes in all) from mission \`${rec.id}\`, written to both.

Both are **testnets**: 0G Galileo tokens and Rabdi tGLM have no market price, so fees are listed in native units and gas, not dollars. Latency, gas, bytes per transaction and what each store can answer are the comparisons that carry over to mainnet.

| | 0G Storage (Galileo) | Arkiv (Rabdi) |
|---|---|---|
${row("Write, median per blob", `${med(z.write).toFixed(0)} ms`, `${med(ak.write).toFixed(0)} ms (one entity per tx)`)}
${row(`Write, all ${blobs.length} at once`, `${z.write.reduce((a, b) => a + b, 0).toFixed(0)} ms (one tx per blob)`, `${ak.batchMs.toFixed(0)} ms (one batch tx)`)}
${row("Gas, all blobs", `${z.gas}`, `${ak.gas} single, ${ak.batchGas} batched`)}
${row("Fee, all blobs (native units)", `${fmt0g(z.fee)} 0G (gas + storage fee)`, `${formatEther(ak.fee)} tGLM single, ${formatEther(ak.batchFee)} tGLM batched`)}
${row("Read back, median", `${med(z.read).toFixed(0)} ms (by root)`, `${med(ak.read).toFixed(0)} ms (by root attribute)`)}
${row("Query by attribute", "not possible: content-addressed blobs", `\`${q.toString()}\` → ${matched} in ${queryMs.toFixed(0)} ms`)}
${row("Lifetime", "permanent", "expires (max ~91 days on Rabdi), extendable")}
${row("Max object size", "large files, chunked", "128 KB per entity")}

**What this means for Blackbox.** 0G Storage stays the archive: permanent, content-addressed, anchored on 0G Chain, which is what the proof needs. Arkiv is the working database next to it: findings you can query by panel, maker or severity, a fleet board, and a mirror the verifier can fall back to. The verifier re-checks every mirrored blob against the hashes anchored on 0G Chain, so the backup cannot change the verdict.
`;
mkdirSync(resolve(REPO_ROOT, "arkiv"), { recursive: true });
writeFileSync(resolve(REPO_ROOT, "arkiv", "benchmark.md"), md);
console.log("\n" + md);
