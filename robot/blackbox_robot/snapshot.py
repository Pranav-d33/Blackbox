"""Export one real mission as a static snapshot for the landing page (works with no backend, e.g. on Vercel).

    python -m blackbox_robot.snapshot ../core/data/missions/<id>.json ../core/web/demo

The flight is regenerated by replay from the robot-signed log (seed + logged answers), so the snapshot's
trajectory hash is the one closed on 0G Chain. Writes mission.json (path, checkpoints, 0G answers, chain
links) and texture.jpg (the world as the 3D view draws it).
"""
from __future__ import annotations

import argparse
import json
import os

from .mission import MissionSim
from .replay import replay
from .sdk import world_meta, world_texture_jpg


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("record", help="core/data/missions/<id>.json")
    ap.add_argument("out", help="output directory, e.g. ../core/web/demo")
    a = ap.parse_args()
    rec = json.load(open(a.record))
    entries = [e for e in rec["entries"] if e]
    r = replay(entries, collect=True)
    if not r["match"]:
        raise SystemExit(f"replay does not match the logged trajectory: {r['mismatches']}")

    m = rec["manifest"]
    sim = MissionSim(m["mission_id"], m["seed"], m["sim"])
    for d in entries[0]["body"].get("defects", []):
        sim.place(d["kind"], d["x_mm"], d["y_mm"], d["variant"])
    for e in entries:
        if e["kind"] == "world" and e["body"].get("defect"):
            d = e["body"]["defect"]
            sim.place(d["kind"], d["x_mm"], d["y_mm"], d["variant"])

    answers = {e["body"]["checkpoint"]: e["body"] for e in entries if e["kind"] in ("decision", "safe_stop", "human")}
    cps = []
    for cp in r["checkpoints"]:
        b = answers.get(cp["k"], {})
        ans = b.get("answer") or {}
        cps.append({
            "k": cp["k"], "asset": cp.get("asset"), "target_mm": cp["target_mm"], "outcome": cp.get("outcome"),
            "label": ans.get("label"), "severity": ans.get("severity"),
            "request_id": (b.get("zg") or {}).get("request_id"), "seq": next((e["seq"] for e in entries if e["kind"] in ("decision", "safe_stop") and e["body"].get("checkpoint") == cp["k"]), None),
        })
    every = max(1, len(r["samples"]) // 900)  # keep the file small: ~900 points is plenty for the 3D path
    os.makedirs(a.out, exist_ok=True)
    snap = {
        "mission_id": m["mission_id"],
        "profile": {k: m["profile"][k] for k in ("id", "title", "ui", "decision")},
        "model": m["policy"].get("vision_model"),
        "attestation": m["policy"].get("attestation", "tee"),
        "chain": {"chain_id": m.get("chain_id"), "registry": m.get("registry"), "register_tx": rec["chain"]["registerTx"], "close_tx": rec["chain"]["closeTx"], "anchors": [x["tx"] for x in rec["chain"]["anchors"]]},
        "manifest_root": rec.get("manifestRoot"),
        "trajectory_hash": r["trajectory_hash"],
        "entries": len(entries),
        "created_at": rec["createdAt"],
        "world": world_meta(sim.world, m["sim"]),
        "home_mm": m["sim"]["home_mm"],
        "waypoints_mm": [list(p) for p in sim.waypoints],
        "samples": r["samples"][::every] + ([r["samples"][-1]] if r["samples"] and (len(r["samples"]) - 1) % every else []),
        "checkpoints": cps,
    }
    with open(os.path.join(a.out, "mission.json"), "w") as f:
        json.dump(snap, f, separators=(",", ":"))
    with open(os.path.join(a.out, "texture.jpg"), "wb") as f:
        f.write(world_texture_jpg(sim.world, max_px=2048))
    sim.close()
    print(f"snapshot of {m['mission_id'][:10]}…: {len(snap['samples'])} samples, {len(cps)} checkpoints, trajectory {r['trajectory_hash'][:12]}… (matches the log)")


if __name__ == "__main__":
    main()
